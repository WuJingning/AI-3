function pickTemplate(contractType) {
  const type = String(contractType || '');
  return TEMPLATES.find((template) => template.match.test(type)) || TEMPLATES[0];
}

export function buildDemoResult(input) {
  const template = pickTemplate(input.contractType);
  const contractText = String(input.text || '').trim();
  const focus = Array.isArray(input.focus) ? input.focus.filter((item) => FOCUS_OPTIONS.includes(item)) : [];
  const usedQuotes = new Set();

  let opinions = template.opinions.map((opinion, index) => ({
    id: `d${index + 1}`,
    level: opinion.level,
    title: opinion.title,
    tags: opinion.tags,
    quote: opinion.keys?.length ? clauseOf(contractText, opinion.keys, opinion.quote, usedQuotes) : opinion.quote,
    analysis: opinion.analysis,
    suggestion: opinion.suggestion,
    legalBasis: opinion.legalBasis,
  }));

  if (focus.length) {
    const matched = opinions.filter((opinion) => opinion.tags.some((tag) => focus.includes(tag)));
    if (matched.length >= 3) opinions = matched;
  }

  const counts = opinions.reduce(
    (acc, opinion) => {
      if (opinion.level === '高') acc.high += 1;
      else if (opinion.level === '中') acc.medium += 1;
      else if (opinion.level === '低') acc.low += 1;
      else acc.unknown += 1;
      acc.total += 1;
      return acc;
    },
    { high: 0, medium: 0, low: 0, unknown: 0, total: 0 }
  );

  const focusText = focus.length ? focus.join('、') : '全部重点领域';
  const conclusion =
    counts.total === 0
      ? '未发现可明确判断的问题，仍需人工复核。'
      : `本次审查共发现 ${counts.total} 条审查意见，其中高风险 ${counts.high} 条、中风险 ${counts.medium} 条、低风险 ${counts.low} 条。建议优先处理高风险条款，并在定稿前完成法务复核。`;

  const extraText = String(input.extra || '').trim();

  return {
    demo: true,
    contract: {
      name: input.contractName || '未命名合同',
      type: input.contractType || template.name,
      stance: input.stance || '中立',
      focus: focus.length ? focus : FOCUS_OPTIONS,
      text: contractText,
      charCount: contractText.length,
      hasText: contractText.length > 0,
    },
    counts,
    conclusion,
    scopeNote: `${STANCE_PREAMBLE[input.stance] || STANCE_PREAMBLE.中立}本次重点审查范围：${focusText}。${extraText ? `补充要求：${extraText}` : ''}`,
    opinions,
    legalCheck: template.legalCheck,
    enterpriseCheck: template.enterpriseCheck,
    reportUrl: '',
    rawOutput: '',
    rawData: null,
    parsed: true,
    demoNotice: '当前为演示结果：未获取到扣子工作流的真实返回，页面使用本地示例数据展示完整交互与结果结构。',
  };
}
