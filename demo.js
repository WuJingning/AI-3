/** 从合同文本中定位与关键词相关的条款片段，用于“原文摘录”与左侧高亮。 */
function clauseOf(text, keywords, fallback, usedQuotes) {
  const source = String(text || '');
  if (!source.trim()) return fallback;
  const clauses = source
    .split(/[\n。；;]+/)
    .map((item) => item.trim())
    .filter((item) => item.length >= 6);

  for (const clause of clauses) {
    const keyword = keywords.find((item) => clause.includes(item));
    if (!keyword) continue;
    let excerpt = clause;
    if (clause.length > 100) {
      const at = clause.indexOf(keyword);
      const start = Math.max(0, at - 30);
      const end = Math.min(clause.length, start + 80);
      excerpt = `${start > 0 ? '…' : ''}${clause.slice(start, end)}${end < clause.length ? '…' : ''}`;
    }
    const normalized = excerpt.replace(/\s+/g, '');
    if (usedQuotes && usedQuotes.has(normalized)) continue;
    if (usedQuotes) usedQuotes.add(normalized);
    return `${excerpt}。`;
  }
  return fallback;
}

